void hsvToRgb(float h, float s, float v, uint8_t &r, uint8_t &g, uint8_t &b) {
  // For fast lookup when s=1 and v=1, use the precalculated table
  if (s >= 0.99f && v >= 0.99f) {
    if (!std::isfinite(h)) {
      r = g = b = 0;
      return;
    }
    h = std::fmod(h, 360.0f);
    if (h < 0.0f)
      h += 360.0f;
    int hue_index = std::clamp(static_cast<int>(h), 0, 359);
    r = hue_to_rgb_table[hue_index][0];
    g = hue_to_rgb_table[hue_index][1];
    b = hue_to_rgb_table[hue_index][2];
    return;
  }

  // Fall back to original calculation for other s/v values
  // Ensure h is in range [0, 360)
  while (h < 0)
    h += 360.0f;
  while (h >= 360.0f)
    h -= 360.0f;

  // Clamp s and v to [0, 1]
  s = std::clamp(s, 0.0f, 1.0f);
  v = std::clamp(v, 0.0f, 1.0f);

  float c = v * s;
  float x = c * (1.0f - fabs(fmod(h / 60.0f, 2.0f) - 1.0f));
  float m = v - c;

  float rp, gp, bp;

  if (h < 60.0f) {
    rp = c;
    gp = x;
    bp = 0;
  } else if (h < 120.0f) {
    rp = x;
    gp = c;
    bp = 0;
  } else if (h < 180.0f) {
    rp = 0;
    gp = c;
    bp = x;
  } else if (h < 240.0f) {
    rp = 0;
    gp = x;
    bp = c;
  } else if (h < 300.0f) {
    rp = x;
    gp = 0;
    bp = c;
  } else {
    rp = c;
    gp = 0;
    bp = x;
  }

  r = (uint8_t)((rp + m) * 255.0f);
  g = (uint8_t)((gp + m) * 255.0f);
  b = (uint8_t)((bp + m) * 255.0f);
}

int signum(double value) {
  if (value > 0) {
    return 1;
  } else if (value < 0) {
    return -1;
  } else {
    return 0;
  }
}

std::unordered_map<std::string, std::string> loadEnv(const std::string &path) {
  std::unordered_map<std::string, std::string> env;
  std::ifstream file(path);
  std::string line;

  while (std::getline(file, line)) {
    // Skip empty lines and comments
    if (line.empty() || line[0] == '#')
      continue;

    auto pos = line.find('=');
    if (pos == std::string::npos)
      continue;

    std::string key = line.substr(0, pos);
    std::string value = line.substr(pos + 1);

    // Trim whitespace
    auto trim = [](std::string &s) {
      s.erase(0, s.find_first_not_of(" \t\r\n"));
      s.erase(s.find_last_not_of(" \t\r\n") + 1);
    };
    trim(key);
    trim(value);

    // Strip surrounding quotes if present
    if (value.size() >= 2 && (value.front() == '"' || value.front() == '\'')) {
      value = value.substr(1, value.size() - 2);
    }

    env[key] = value;
    setenv(key.c_str(), value.c_str(),
           1); // also put it in the real environment (POSIX)
  }

  return env;
}

